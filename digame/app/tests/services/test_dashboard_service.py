async def test_remove_widget_from_dashboard(dashboard_service: DashboardService, sample_tenant_id: int, sample_user_id: int, sample_widget_config_data: dict):
    dashboard = await dashboard_service.create_custom_dashboard(sample_tenant_id, sample_user_id, "Remove Widget Test")

    widget1_data = sample_widget_config_data.copy()
    widget1_data["title"] = "Widget 1"
    widget1 = WidgetConfig(id=str(uuid.uuid4()), **widget1_data)

    widget2_data = sample_widget_config_data.copy()
    widget2_data["title"] = "Widget 2"
    widget2_data["widget_type"] = "benchmark_comparison"
    widget2 = WidgetConfig(id=str(uuid.uuid4()), **widget2_data)

    await dashboard_service.add_widget_to_dashboard(dashboard.id, sample_user_id, widget1)
    await dashboard_service.add_widget_to_dashboard(dashboard.id, sample_user_id, widget2)

    dashboard_with_widgets = await dashboard_service.get_custom_dashboard(dashboard.id, sample_user_id)
    assert len(dashboard_with_widgets.layout.widgets) == 2

    # Remove widget1
    updated_dashboard = await dashboard_service.remove_widget_from_dashboard(dashboard.id, sample_user_id, widget1.id)
    assert updated_dashboard is not None
    assert len(updated_dashboard.layout.widgets) == 1
    assert updated_dashboard.layout.widgets[0].id == widget2.id

    # Try removing non-existent widget
    no_change_dashboard = await dashboard_service.remove_widget_from_dashboard(dashboard.id, sample_user_id, str(uuid.uuid4()))
    assert len(no_change_dashboard.layout.widgets) == 1



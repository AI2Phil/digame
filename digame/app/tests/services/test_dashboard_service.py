# --- Test Custom Dashboard Management ---

async def test_create_custom_dashboard(dashboard_service: DashboardService, sample_tenant_id: int, sample_user_id: int):
    name = "My Test Dashboard"
    description = "A dashboard for testing"
    dashboard = await dashboard_service.create_custom_dashboard(
        tenant_id=sample_tenant_id,
        user_id=sample_user_id,
        name=name,
        description=description
    )
    assert dashboard.name == name
    assert dashboard.description == description
    assert dashboard.user_id == sample_user_id
    assert dashboard.tenant_id == sample_tenant_id
    assert dashboard.id in dashboard_service._custom_dashboards
    assert dashboard.layout.columns == 12
    assert len(dashboard.layout.widgets) == 0

async def test_get_custom_dashboard(dashboard_service: DashboardService, sample_tenant_id: int, sample_user_id: int):
    created_dashboard = await dashboard_service.create_custom_dashboard(sample_tenant_id, sample_user_id, "Test Dash")

    fetched_dashboard = await dashboard_service.get_custom_dashboard(created_dashboard.id, sample_user_id)
    assert fetched_dashboard is not None
    assert fetched_dashboard.id == created_dashboard.id

    # Test access by wrong user
    wrong_user_dashboard = await dashboard_service.get_custom_dashboard(created_dashboard.id, sample_user_id + 1)
    assert wrong_user_dashboard is None

    # Test non-existent dashboard
    non_existent_dashboard = await dashboard_service.get_custom_dashboard(str(uuid.uuid4()), sample_user_id)
    assert non_existent_dashboard is None

